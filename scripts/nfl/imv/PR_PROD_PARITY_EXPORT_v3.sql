BEGIN TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY;
SET LOCAL statement_timeout = '60s';
SET LOCAL idle_in_transaction_session_timeout = '120s';
SET LOCAL TIME ZONE 'UTC';

COPY (
  WITH sched AS (
    SELECT s.season, s.week, s.game_id, s.game_date, s.home_team, s.away_team,
           s.game_type, s.roof, s.updated_at
    FROM public.nfl_dp_schedules AS s
    WHERE s.game_type = 'REG'
      AND (s.season = 2025 OR (s.season = 2026 AND s.week <= 7))
  ),
  sched_dups AS (
    SELECT count(*) AS dup_keys FROM (
      SELECT season, game_id FROM sched GROUP BY season, game_id HAVING count(*) > 1
    ) d
  ),
  team_games AS (
    SELECT season, week, game_id, game_date, home_team AS team FROM sched
    UNION ALL
    SELECT season, week, game_id, game_date, away_team AS team FROM sched
  ),
  team_rest AS (
    SELECT season, game_id, team, game_date,
           LAG(game_date) OVER (PARTITION BY team ORDER BY season, week, game_date) AS prev_reg_game_date
    FROM team_games
  )
  SELECT
    m.season,
    m.week,
    m.game_id,
    m.game_date,
    m.home_team,
    m.away_team,
    m.home_off_epa_5g,
    m.away_off_epa_5g,
    m.home_def_epa_allowed_5g,
    m.away_def_epa_allowed_5g,
    m.home_pass_rate_5g,
    m.away_pass_rate_5g,
    m.home_success_offense_5g,
    m.away_success_offense_5g,
    m.home_pressure_allowed_5g,
    m.away_pressure_allowed_5g,
    m.home_pressure_generated_5g,
    m.away_pressure_generated_5g,
    m.home_early_down_pass_rate_5g,
    m.away_early_down_pass_rate_5g,
    m.home_red_zone_td_rate_5g,
    m.away_red_zone_td_rate_5g,
    m.home_success_defense_allowed_5g,
    m.away_success_defense_allowed_5g,
    m.diff_off_epa_5g,
    m.updated_at AS feature_updated_at,
    s.game_type AS schedule_game_type,
    s.roof AS schedule_roof,
    s.game_date AS schedule_game_date,
    s.updated_at AS schedule_updated_at,
    (s.game_date::date - rh.prev_reg_game_date::date) AS home_rest_days,
    (s.game_date::date - ra.prev_reg_game_date::date) AS away_rest_days,
    rh.prev_reg_game_date AS home_prev_reg_game_date,
    ra.prev_reg_game_date AS away_prev_reg_game_date,
    CASE WHEN lower(s.roof) IN ('dome','closed') THEN 1
         WHEN lower(s.roof) IN ('outdoors','open') THEN 0
         ELSE NULL END AS roof_dome,
    (s.roof IS NOT NULL AND lower(s.roof) NOT IN ('dome','closed','outdoors','open')) AS roof_vocab_unknown,
    max(m.updated_at) OVER () AS feature_as_of_max_utc,
    max(s.updated_at) OVER () AS schedule_as_of_max_utc,
    count(*) OVER () AS export_row_count,
    count(*) OVER (PARTITION BY m.week, m.game_id) AS export_distinct_week_game_count_per_key,
    (SELECT dup_keys FROM sched_dups) AS schedule_dup_game_rows
  FROM public.nfl_dp_matchup_features_weekly AS m
  LEFT JOIN sched AS s
    ON s.season = m.season AND s.game_id = m.game_id
  LEFT JOIN team_rest AS rh
    ON rh.season = s.season AND rh.game_id = s.game_id AND rh.team = s.home_team
  LEFT JOIN team_rest AS ra
    ON ra.season = s.season AND ra.game_id = s.game_id AND ra.team = s.away_team
  WHERE m.season = 2026
    AND m.week BETWEEN 3 AND 7
    AND s.game_type = 'REG'
  ORDER BY m.week, m.game_id
) TO STDOUT WITH (FORMAT csv, HEADER true);

ROLLBACK;
